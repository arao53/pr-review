def test_reexports_and_attribute_access():
    g = build_graph({
        "pkg/__init__.py": "from .core import Option, echo as say\n",
        "pkg/core.py": "class Option: pass\ndef echo(): pass\n",
        "tests/test_a.py": "import pkg\n\ndef test():\n    pkg.Option()\n",
        "tests/test_b.py": "from pkg import say\n",
    })
    assert ("tests/test_a.py", "pkg/core.py") in g.g.edges
    assert "Option" in g.g.edges["tests/test_a.py", "pkg/core.py"]["names"]
    assert ("tests/test_b.py", "pkg/core.py") in g.g.edges


def test_api_compatibility():
    def change(old, new):
        (c,) = [x for x in pyast.api_changes(old, new) if x["change"] == "changed"]
        return c["compatible"]

    assert change("def f(a, b): pass", "def f(a, b, c=None): pass")
    assert change("def f(a): pass", "def f(a: int) -> str: pass")
    assert change("def f(a, *, k=1): pass", "def f(a, *, k=1, j=2): pass")
    assert not change("def f(a, b): pass", "def f(a, b, c): pass")
    assert not change("def f(a, b): pass", "def f(b, a): pass")
    assert not change("def f(a, *, k=1): pass", "def f(a): pass")
    assert change("class C(Base): pass", "class C(Base[int]): pass")
    assert not change("class C(Base): pass", "class C(Other): pass")
