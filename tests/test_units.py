def test_html_escapes_script_tags():
    review = {"meta": {"note": "</script><script>alert(1)</script> <!-- x"}}
    html = render_html(review)
    assert "</script><script>alert(1)" not in html
    assert html.count("</script>") == 2  # data block + app script
    start = html.index('type="application/json">') + len('type="application/json">')
    embedded = html[start:html.index("</script>", start)]
    assert json.loads(embedded) == review


def test_cli_end_to_end(shop_repo, monkeypatch):
    monkeypatch.chdir(shop_repo.root)
    runner = CliRunner()
    res = runner.invoke(main, ["analyze", "--base", "main"])
    assert res.exit_code == 0, res.output
    assert "Clusters (1)" in res.output
    out = shop_repo.root / ".pr-review" / "feature"
    assert (out / "review.json").exists() and (out / "report.html").exists()
    assert (shop_repo.root / ".pr-review" / ".gitignore").read_text() == "*\n"

    res = runner.invoke(main, ["summary", "--cluster", "c1", "--json"])
    data = json.loads(res.output)
    assert all(f["diff"] is None for f in data["files"])

    # a reviewer adds a finding, then re-renders
    review = json.loads((out / "review.json").read_text())
    review["clusters"][0]["findings"].append({"severity": "high", "title": "Secret committed", "file": "src/shop/auth/session.py", "line": 4})
    (out / "review.json").write_text(json.dumps(review))
    res = runner.invoke(main, ["report"])
    assert res.exit_code == 0
    assert "Secret committed" in (out / "report.html").read_text()


