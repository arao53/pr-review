def test_same_ast_ignores_formatting_only():
    assert pyast.same_ast("x=[1,2]\n", "x = [\n    1,\n    2,\n]  # c\n")
    assert not pyast.same_ast("x = 1\n", "x = 2\n")
    assert not pyast.same_ast("x = (\n", "x = 1\n")  # unparsable never counts as cosmetic


def test_api_respects_dunder_all():
    src = "__all__ = ['a']\ndef a(): pass\ndef b(): pass\n"
    assert set(pyast.public_api(src)) == {"a"}


def test_signals_only_on_added_lines():
    src = "try:\n    x()\nexcept:\n    pass\ntry:\n    y()\nexcept:\n    pass\n"
    sigs = pyast.scan_signals(src, {7})
    assert [s["line"] for s in sigs] == [7]


def test_relative_and_src_layout_imports():
    g = build_graph({
        "src/pkg/__init__.py": "",
        "src/pkg/a.py": "from . import b\nfrom .sub.c import thing\n",
        "src/pkg/b.py": "import pkg.sub.c\n",
        "src/pkg/sub/__init__.py": "",
        "src/pkg/sub/c.py": "from ..b import helper\nthing = 1\n",
        "tests/test_a.py": "from pkg.a import *\n",
    })
    edges = set(g.g.edges())
    assert ("src/pkg/a.py", "src/pkg/b.py") in edges
    assert ("src/pkg/a.py", "src/pkg/sub/c.py") in edges
    assert ("src/pkg/b.py", "src/pkg/sub/c.py") in edges
    assert ("src/pkg/sub/c.py", "src/pkg/b.py") in edges
    assert ("tests/test_a.py", "src/pkg/a.py") in edges
    assert "helper" in g.g.edges["src/pkg/sub/c.py", "src/pkg/b.py"]["names"]


