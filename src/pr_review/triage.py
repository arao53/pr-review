"""Path-level classification: what kind of file is this, and does a reviewer
need to read it at all?"""

from __future__ import annotations

import posixpath
import re

LOCKFILES = {
    "poetry.lock", "uv.lock", "pdm.lock", "pipfile.lock", "package-lock.json",
    "yarn.lock", "pnpm-lock.yaml", "cargo.lock", "go.sum", "gemfile.lock", "composer.lock",
}
DEPENDENCY_FILES = {
    "pyproject.toml", "setup.py", "setup.cfg", "pipfile", "environment.yml",
    "environment.yaml", "package.json",
}
GENERATED_DIRS = {"vendor", "node_modules", "dist", "build", "__snapshots__", "_vendor", "site-packages"}
GENERATED_SUFFIXES = (
    "_pb2.py", "_pb2.pyi", "_pb2_grpc.py", ".min.js", ".min.css", ".snap", ".map",
)
GENERATED_HEADER = re.compile(
    r"@generated|do not edit|code generated|auto-?generated|generated by the protocol buffer",
    re.IGNORECASE,
)
DOC_EXT = {".md", ".rst", ".txt", ".adoc"}
CONFIG_EXT = {".toml", ".yaml", ".yml", ".json", ".ini", ".cfg", ".env", ".conf"}
TEST_DIRS = {"tests", "test", "testing"}


def _parts(path: str) -> list[str]:
    return path.lower().split("/")


def lockfile_reason(path: str) -> str | None:
    return "lockfile" if posixpath.basename(path).lower() in LOCKFILES else None


def generated_reason(path: str, new_text: str | None) -> str | None:
    """Why this file can be skipped as generated, or None."""
    lower = path.lower()
    base = posixpath.basename(lower)
    if base in LOCKFILES:
        return "lockfile"
    if any(p in GENERATED_DIRS for p in _parts(path)[:-1]):
        return "vendored or build output"
    if lower.endswith(GENERATED_SUFFIXES) or ".egg-info/" in lower:
        return "generated artifact"
    if new_text and category(path) != "migration":
        head = "\n".join(new_text.splitlines()[:5])
        if GENERATED_HEADER.search(head):
            return "generated-file header"
    return None


def is_test(path: str) -> bool:
    parts = _parts(path)
    base = parts[-1]
    if base == "conftest.py":
        return True
    if base.startswith("test_") or base.endswith("_test.py") or base == "tests.py":
        return True
    return any(p in TEST_DIRS for p in parts[:-1])


def category(path: str) -> str:
    parts = _parts(path)
    base = parts[-1]
    ext = posixpath.splitext(base)[1]
    if base in LOCKFILES or base in DEPENDENCY_FILES or (base.startswith("requirements") and ext in (".txt", ".in")):
        return "dependency"
    if "migrations" in parts[:-1] or ("alembic" in parts and "versions" in parts):
        if ext in (".py", ".sql"):
            return "migration"
    if ext == ".py" and is_test(path):
        return "test"
    if (
        ".github" in parts or base in ("dockerfile", "makefile", "tox.ini", "noxfile.py", ".pre-commit-config.yaml",
                                       ".gitlab-ci.yml", "docker-compose.yml", "docker-compose.yaml")
        or base.startswith("dockerfile")
    ):
        return "ci"
    if ext == ".py":
        return "source"
    if ext in DOC_EXT or "docs" in parts[:-1] or base.startswith("readme"):
        return "docs"
    if ext in CONFIG_EXT:
        return "config"
    return "other"


def language(path: str) -> str | None:
    ext = posixpath.splitext(path)[1].lower()
    return {".py": "python", ".pyi": "python"}.get(ext, ext.lstrip(".") or None)


SENSITIVE = re.compile(
    r"(^|[/_.-])(auth\w*|login|logout|passwords?|passwd|secrets?|tokens?|crypto\w*|security|"
    r"permissions?|acl|rbac|payments?|billing|stripe|invoices?|sessions?|oauth\w*|jwt|settings|"
    r"middleware|signing|encrypt\w*|sanitiz\w*|admin)([/_.-]|$)",
    re.IGNORECASE,
)


def sensitive_reason(path: str) -> str | None:
    m = SENSITIVE.search(path)
    return f"sensitive path ({m.group(2).lower()})" if m else None
